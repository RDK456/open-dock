// Run: node scripts/sync-pet.ts
// Copies the pet (pc-companion/src/pet/pet.js) into phone-app/src/pet-source.ts, where the phone's widget page loads it.
import { readFileSync, writeFileSync } from 'node:fs';

// Line endings depend on the checkout (core.autocrlf), so the phone copy always uses LF.
const source = readFileSync(new URL('../pc-companion/src/pet/pet.js', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
writeFileSync(
  new URL('../phone-app/src/pet-source.ts', import.meta.url),
  `// Generated by scripts/sync-pet.ts from pc-companion/src/pet/pet.js. Do not edit.\nexport const PET_SOURCE = ${JSON.stringify(source)};\n`,
);
console.log('phone-app/src/pet-source.ts updated');
